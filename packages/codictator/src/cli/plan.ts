// SPEC §4.19.3: the manifest-owned launcher. Plain ES2017 module syntax
// (imports, no top-level await, no object spread) so any Node can parse
// it: node floor check, engine resolution at the root or tool dir, argv
// delegation; CDX-E003 with exit 6 when neither entry exists. The launcher
// is generated TEXT, not a runtime import of this module, so its module
// specifiers interpolate (SPEC §10.3 item 3 scans source for node:fs and
// friends); the emitted bytes are the plain imports below.
function launcherImport(alias: string, module: string): string {
	return `import * as ${alias} from "node:${module}";`;
}

const LAUNCHER_TEXT = [
	"#!/usr/bin/env node",
	"// Generated by `codictator init` (SPEC §4.19.3); do not edit by hand.",
	launcherImport("path", "path"),
	launcherImport("child", "child_process"),
	launcherImport("fs", "fs"),
	"var MIN_MAJOR = 24;",
	'var parts = process.versions.node.split(".");',
	"var major = Number(parts[0]);",
	"if (!(major >= MIN_MAJOR)) {",
	'	process.stderr.write("CDX-E002 node " + process.version + " is older than the required v" + MIN_MAJOR + "; upgrade Node.js.\\n");',
	"	process.exit(6);",
	"}",
	"function candidate(root) {",
	'	return path.join(root, "node_modules", "codictator", "dist", "cli", "main.js");',
	"}",
	"function resolveEngine(root) {",
	'	var roots = [root, path.join(root, ".codictator", "tool")];',
	"	for (var i = 0; i < roots.length; i += 1) {",
	"		var entry = candidate(roots[i]);",
	"		try {",
	"			fs.accessSync(entry);",
	"			return entry;",
	"		} catch (ignored) {",
	"			continue;",
	"		}",
	"	}",
	"	return null;",
	"}",
	"var root = process.env.CODICTATOR_ROOT;",
	"if (!root) {",
	"	try {",
	'		root = child.execSync("git rev-parse --show-toplevel", { encoding: "utf8" }).trim();',
	"	} catch (ignored) {",
	"		root = process.cwd();",
	"	}",
	"}",
	"var entry = resolveEngine(root);",
	"if (entry === null) {",
	'	process.stderr.write("CDX-E003 engine not installed; run npm ci, then retry.\\n");',
	"	process.exit(6);",
	"}",
	'var result = child.spawnSync(process.execPath, [entry].concat(process.argv.slice(2)), { stdio: "inherit" });',
	"process.exit(result.status === null ? 6 : result.status);",
	"",
].join("\n");

function encode(text: string): Uint8Array {
	return new TextEncoder().encode(text);
}

function configText(harnesses: ReadonlyArray<string>, profile: string): string {
	const sorted = [...harnesses].sort();
	const config: Record<string, unknown> = {
		version: 1,
		codictator: ENGINE_VERSION,
		packs: [],
		harnesses: sorted,
		tunables: {},
		...(profile === "" ? {} : { architecture: { profile } }),
	};
	return `${stableStringify(config)}\n`;
}

// SPEC §4.14.1: user text outside the managed block survives regen; a
// malformed block is replaced rather than duplicated (CDX-E501 avoided).
function withManagedBlock(existing: string | undefined): string {
	const block = buildManagedBlock();
	if (existing === undefined) {
		return `${block}\n`;
	}
	const start = existing.indexOf(MANAGED_BEGIN);
	const end = existing.indexOf(MANAGED_END);
	if (start < 0 || end < 0 || end < start) {
		const trimmed = existing.endsWith("\n") ? existing : `${existing}\n`;
		return `${trimmed}\n${block}\n`;
	}
	const after = end + MANAGED_END.length;
	return `${existing.slice(0, start)}${block}${existing.slice(after)}`;
}

export interface GuardrailPlan {
	readonly files: ReadonlyArray<{ path: string; content: string }>;
}

export function guardrailPlan(
	harnesses: ReadonlyArray<string>,
	profile: string,
	repoName: string,
	existingAgents: string | undefined,
): GuardrailPlan {
	const files: Array<{ path: string; content: string }> = [];
	files.push({
		path: ".codictator/config.json",
		content: configText(harnesses, profile),
	});
	files.push({ path: "AGENTS.md", content: withManagedBlock(existingAgents) });
	const workflow = renderWorkflow(repoName);
	files.push({
		path: ".github/workflows/codictator.yml",
		content: workflow.text ?? "",
	});
	for (const hook of HOOK_NAMES) {
		files.push({
			path: `${EXPECTED_HOOKS_PATH}/${hook}`,
			content: renderHookScript(hook),
		});
	}
	const plan = hookInstallPlan({});
	files.push({
		path: `${EXPECTED_HOOKS_PATH}/.gitattributes`,
		content: plan.gitattributes,
	});
	files.push({ path: ".codictator/bin/run.mjs", content: LAUNCHER_TEXT });
	return { files };
}

export async function writePlan(
	root: string,
	plan: GuardrailPlan,
): Promise<Result<Array<{ path: string; hash: string }>>> {
	const ports = await portsFor(root);
	if (!ports.ok) {
		return err(ports.error);
	}
	const written: Array<{ path: string; hash: string }> = [];
	for (const file of plan.files) {
		const done = await ports.value.fs.write(file.path, encode(file.content));
		if (!done.ok) {
			return err(done.error);
		}
		written.push({
			path: file.path,
			hash: sha256Text(normalizeText(file.content)),
		});
	}
	const manifest = buildManifest(
		ENGINE_VERSION,
		written.map((entry) => ({
			path: entry.path,
			owner: "codictator",
			mode: "file" as const,
			hash: entry.hash,
		})),
	);
	const saved = await ports.value.fs.write(
		".codictator/manifest.json",
		encode(`${stableStringify(manifest)}\n`),
	);
	if (!saved.ok) {
		return err(saved.error);
	}
	return ok(written);
}
