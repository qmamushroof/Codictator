// SPEC §4.8.7: Codictator's own upgrade changes. Planning is pure over
// caller-supplied manifest and history text; pushing runs through the host
// port the caller implements, so this module never touches the OS (§3.3).
// One branch per dependency, grouping patch and minor of the same package
// line; majors become remediation chains (§4.13.5), never single PRs.

import type { Result } from "../../kernel/index.ts";
import { makeError } from "../../kernel/index.ts";
import { upgradeBranchName } from "./bots.ts";

export interface UpgradeFile {
	readonly path: string;
	readonly text: string;
}

export interface UpgradePrInput {
	readonly ecosystem: string;
	readonly name: string;
	readonly from: string;
	readonly to: string;
	readonly manifestPath: string;
	readonly manifestText: string;
	readonly historyText?: string | undefined;
	readonly historyPath?: string | undefined;
	readonly date: string;
	readonly task?: string | undefined;
	readonly advisoryIds?: ReadonlyArray<string> | undefined;
	readonly lockfilePath?: string | undefined;
	readonly lockfileText?: string | undefined;
}

export interface UpgradePrPlan {
	readonly branch: string;
	readonly subject: string;
	readonly files: ReadonlyArray<UpgradeFile>;
}

export interface UpgradeHost {
	readonly createBranch: (branch: string) => Promise<Result<void>>;
	readonly writeFiles: (
		files: ReadonlyArray<UpgradeFile>,
	) => Promise<Result<void>>;
	readonly commit: (message: string) => Promise<Result<void>>;
	readonly push: (branch: string) => Promise<Result<void>>;
}

// The commit subject doubles as the history entry Subject (§4.9.3 unit rule),
// and satisfies core/conventional-commit on its own (chore with a deps scope).
export function upgradeCommitSubject(
	name: string,
	from: string,
	to: string,
): string {
	return `chore(deps): upgrade ${name} ${from} to ${to}`;
}

// SPEC §7.7: a deps entry carries Kind, Task, Why and one Deps line per
// change in the added, upgraded or removed form.
export function upgradeHistoryEntry(
	date: string,
	subject: string,
	name: string,
	from: string,
	to: string,
	task: string,
	advisoryIds: ReadonlyArray<string>,
): string {
	const rendered =
		advisoryIds.length === 0 ? "none" : [...advisoryIds].sort().join(", ");
	return [
		`## ${date} · ${subject}`,
		`- **Kind:** deps`,
		`- **Task:** ${task}`,
		`- **Why:** L5 sweep upgrades ${name} to latest stable ${to} (SPEC §4.8.7).`,
		`- **Deps:** ↑ ${name} ${from} → ${to} — ${rendered}`,
	].join("\n");
}

function escapeRegExp(value: string): string {
	return value.replaceAll(/[$()*+.?[\\\]^{|}]/g, "\\$&");
}

function bumpManifestPin(
	manifestText: string,
	name: string,
	from: string,
	to: string,
): Result<string> {
	const pattern = new RegExp(
		`"${escapeRegExp(name)}"\\s*:\\s*"${escapeRegExp(from)}"`,
	);
	if (!pattern.test(manifestText)) {
		return {
			ok: false,
			error: makeError(
				"CDX-E903",
				`${name} is not pinned at ${from} in the supplied manifest`,
				`Supply the manifest text pinning ${name} at ${from}, or re-resolve the upgrade.`,
			),
		};
	}
	return {
		ok: true,
		value: manifestText.replace(pattern, `"${name}": "${to}"`),
	};
}

function appendHistoryEntry(
	historyText: string | undefined,
	date: string,
	entry: string,
): string {
	const day = date.slice(0, 10);
	if (historyText === undefined || historyText.trim() === "") {
		return `# History — ${day}\n\n${entry}\n`;
	}
	const endOfTitle = historyText.indexOf("\n");
	if (endOfTitle < 0) {
		return `${historyText}\n\n${entry}\n`;
	}
	const title = historyText.slice(0, endOfTitle);
	const rest = historyText.slice(endOfTitle + 1).replace(/^\n+/, "");
	if (rest === "") {
		return `${title}\n\n${entry}\n`;
	}
	return `${title}\n\n${entry}\n\n${rest.endsWith("\n") ? rest : `${rest}\n`}`;
}

// SPEC §4.8.7: the PR holds the manifest edit, the regenerated lockfile and
// its history entry. The lockfile bytes come from the caller (regenerated by
// the ecosystem tool); without them the plan holds manifest plus history.
export function planUpgradePr(input: UpgradePrInput): Result<UpgradePrPlan> {
	if (!/^\d{4}-\d{2}-\d{2}$/.test(input.date)) {
		return {
			ok: false,
			error: makeError(
				"CDX-E903",
				`upgrade date ${input.date} is not a UTC YYYY-MM-DD date`,
				"Pass the commit date in UTC as YYYY-MM-DD.",
			),
		};
	}
	const bumped = bumpManifestPin(
		input.manifestText,
		input.name,
		input.from,
		input.to,
	);
	if (!bumped.ok) {
		return bumped;
	}
	const subject = upgradeCommitSubject(input.name, input.from, input.to);
	const entry = upgradeHistoryEntry(
		input.date,
		subject,
		input.name,
		input.from,
		input.to,
		input.task ?? "none",
		input.advisoryIds ?? [],
	);
	const historyPath =
		input.historyPath ?? `docs/HISTORY/${input.date.slice(0, 10)}.md`;
	const files: Array<UpgradeFile> = [
		{ path: input.manifestPath, text: bumped.value },
		{
			path: historyPath,
			text: appendHistoryEntry(input.historyText, input.date, entry),
		},
	];
	if (input.lockfilePath !== undefined && input.lockfileText !== undefined) {
		files.push({ path: input.lockfilePath, text: input.lockfileText });
	}
	return {
		ok: true,
		value: {
			branch: upgradeBranchName(input.ecosystem, input.name, input.to),
			subject,
			files,
		},
	};
}

// One step, one PR: the branch is created from the base, committed with its
// history entry, and pushed through the host API with the CI token. Nothing
// is pushed to the default branch.
export async function runUpgradePr(
	plan: UpgradePrPlan,
	host: UpgradeHost,
): Promise<Result<UpgradePrPlan>> {
	const branched = await host.createBranch(plan.branch);
	if (!branched.ok) {
		return branched;
	}
	const written = await host.writeFiles(plan.files);
	if (!written.ok) {
		return written;
	}
	const committed = await host.commit(plan.subject);
	if (!committed.ok) {
		return committed;
	}
	const pushed = await host.push(plan.branch);
	if (!pushed.ok) {
		return pushed;
	}
	return { ok: true, value: plan };
}
