// SPEC §4.20: the extension-host E2E smoke. Runs under plain node:test
// (no display, no download): the tmp fixture mirrors setup output, links
// the built engine, and pins a real version. The in-host suite in
// suite/index.mjs owns the live asserts (PR1 root and version asserts,
// PR2 ping and watcher-push gates landed there); the smoke pins the
// protocol shape (initialize plus ping) so a broken serve surface fails
// fast. The remaining gates wait on PRs 3-4 per the Roadmap 11 exit gate.
import { strict as assert } from "node:assert";
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve, sep } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import {
	createE2eFixture,
	removeE2eFixture,
} from "../../scripts/e2e-fixture.mjs";
import { openServeSession } from "../../scripts/serve-client.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..", "..", "..");
const enginePackageDir = join(repoRoot, "packages", "codictator");

test("[§4.20] e2e fixture mirrors setup output and links the built engine", async () => {
	const fixture = await createE2eFixture({ enginePackageDir });
	try {
		const raw = readFileSync(fixture.configPath, "utf8");
		const config = JSON.parse(raw);
		assert.equal(config.version, 1);
		assert.equal(existsSync(fixture.launcherPath), true);
		assert.match(readFileSync(fixture.launcherPath, "utf8"), /Generated by/);
		assert.equal(existsSync(fixture.engineEntry), true);
		assert.ok(fixture.dir.startsWith(tmpdir() + sep));
		assert.notEqual(fixture.dir, process.cwd());
	} finally {
		removeE2eFixture(fixture.dir);
	}
	assert.equal(existsSync(fixture.dir), false);
});

test("[§4.20] e2e fixture pins the built engine version, never 0.0.0", async () => {
	const fixture = await createE2eFixture({ enginePackageDir });
	try {
		assert.notEqual(fixture.engineVersion, "");
		assert.notEqual(fixture.engineVersion, "0.0.0");
		const config = JSON.parse(readFileSync(fixture.configPath, "utf8"));
		assert.equal(config.packs[0].version, fixture.engineVersion);
		for (const pack of config.packs) {
			assert.notEqual(pack.version, "", `pack ${pack.id} names a version`);
			assert.notEqual(
				pack.version,
				"0.0.0",
				`pack ${pack.id} pins a real version`,
			);
		}
	} finally {
		removeE2eFixture(fixture.dir);
	}
});

test("[§4.20] e2e runner uses the SPEC §2 @vscode/test-electron pin", () => {
	const rootManifest = JSON.parse(
		readFileSync(join(repoRoot, "package.json"), "utf8"),
	);
	const pinned = rootManifest.devDependencies?.["@vscode/test-electron"];
	assert.ok(
		typeof pinned === "string" && pinned !== "",
		`root manifest pins @vscode/test-electron`,
	);
	assert.notEqual(pinned, "0.0.0");
	const installed = JSON.parse(
		readFileSync(
			join(
				repoRoot,
				"node_modules",
				"@vscode",
				"test-electron",
				"package.json",
			),
			"utf8",
		),
	);
	assert.equal(
		installed.version,
		pinned,
		`installed test-electron matches the SPEC §2 pin`,
	);
});

test("[§4.20] e2e engine answers initialize and ping over stdio", async () => {
	const fixture = await createE2eFixture({ enginePackageDir });
	const session = openServeSession(fixture.launcherPath, fixture.dir);
	try {
		const init = await session.request("initialize", {});
		assert.equal(init.protocolVersion, 1);
		assert.equal(init.engineVersion, fixture.engineVersion);
		assert.notEqual(init.engineVersion, "0.0.0");
		const pong = await session.request("ping", {});
		assert.deepEqual(pong, { pong: true });
	} finally {
		await session.close();
		removeE2eFixture(fixture.dir);
	}
	assert.equal(existsSync(fixture.dir), false);
});

test("[§4.20] run-e2e --smoke-only wires the fixture without a VS Code launch", () => {
	const runner = join(repoRoot, "packages", "vscode", "scripts", "run-e2e.mjs");
	const result = spawnSync(process.execPath, [runner, "--smoke-only"], {
		cwd: repoRoot,
		encoding: "utf8",
		timeout: 120_000,
	});
	assert.equal(
		result.status,
		0,
		`runner exits 0:\n${result.stdout}\n${result.stderr}`,
	);
	assert.match(
		result.stdout,
		/smoke-only: fixture wiring ok, no VS Code launch/,
	);
	assert.match(result.stdout, /fixture: .*codictator-e2e-/);
	assert.ok(
		result.stdout.includes(`host cwd: ${repoRoot}`),
		`host cwd stays at the repo root:\n${result.stdout}`,
	);
});
