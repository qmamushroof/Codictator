// SPEC §4.20: the extension-host E2E smoke. Runs under plain node:test
// (no display, no download): the tmp fixture mirrors setup output, links
// the built engine, and pins a real version. The in-host suite in
// suite/index.mjs owns the live asserts; the rest waits on PRs 1-3 per
// the Roadmap 11 exit gate.
import { strict as assert } from "node:assert";
import { existsSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve, sep } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import {
	createE2eFixture,
	removeE2eFixture,
} from "../../scripts/e2e-fixture.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..", "..", "..");
const enginePackageDir = join(repoRoot, "packages", "codictator");

test("[§4.20] e2e fixture mirrors setup output and links the built engine", async () => {
	const fixture = await createE2eFixture({ enginePackageDir });
	try {
		const raw = readFileSync(fixture.configPath, "utf8");
		const config = JSON.parse(raw);
		assert.equal(config.version, 1);
		assert.equal(existsSync(fixture.launcherPath), true);
		assert.match(readFileSync(fixture.launcherPath, "utf8"), /Generated by/);
		assert.equal(existsSync(fixture.engineEntry), true);
		assert.ok(fixture.dir.startsWith(tmpdir() + sep));
		assert.notEqual(fixture.dir, process.cwd());
	} finally {
		removeE2eFixture(fixture.dir);
	}
	assert.equal(existsSync(fixture.dir), false);
});

test("[§4.20] e2e fixture pins the built engine version, never 0.0.0", async () => {
	const fixture = await createE2eFixture({ enginePackageDir });
	try {
		assert.notEqual(fixture.engineVersion, "");
		assert.notEqual(fixture.engineVersion, "0.0.0");
		const config = JSON.parse(readFileSync(fixture.configPath, "utf8"));
		assert.equal(config.packs[0].version, fixture.engineVersion);
	} finally {
		removeE2eFixture(fixture.dir);
	}
});
