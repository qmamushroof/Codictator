// SPEC §4.20: the extension-host E2E fixture. A tmp repo shaped like
// `codictator init` output (config.json plus the launcher at
// .codictator/bin/run.mjs) whose launcher resolves the built engine from
// this checkout, so the host under test spawns the real server. The repo
// lives under the OS tmp dir, never under the host cwd, which is the D1
// regression shape. Full view asserts wait on PRs 1-3 per the Roadmap 11
// exit gate.
import {
	existsSync,
	mkdirSync,
	mkdtempSync,
	readFileSync,
	rmSync,
	symlinkSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { isAbsolute, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

function engineVersionOf(enginePackageDir) {
	const raw = readFileSync(join(enginePackageDir, "package.json"), "utf8");
	const parsed = JSON.parse(raw);
	if (typeof parsed !== "object" || parsed === null) {
		throw new Error(`engine package.json is not an object`);
	}
	const version = parsed.version;
	if (typeof version !== "string" || version === "") {
		throw new Error(`engine package.json names no version`);
	}
	return version;
}

async function launcherTextOf(enginePackageDir) {
	const moduleUrl = pathToFileURL(
		join(enginePackageDir, "dist", "cli", "plan-launcher.js"),
	).href;
	const launcher = await import(moduleUrl);
	const text = launcher.LAUNCHER_TEXT;
	if (typeof text !== "string" || !text.includes("Generated by")) {
		throw new Error(
			`built engine has no launcher text; run npm run build first`,
		);
	}
	return text.endsWith("\n") ? text : `${text}\n`;
}

function fixtureConfig(engineVersion) {
	return (
		JSON.stringify({
			architecture: { modules: [], profile: "app" },
			codictator: engineVersion,
			harnesses: ["opencode"],
			packs: [{ id: "core", version: engineVersion }],
			tools: [],
			tunables: {},
			version: 1,
		}) + "\n"
	);
}

// Build the fixture repo. enginePackageDir must be absolute and point at
// the built codictator package (dist/ present). Returns the repo paths.
export async function createE2eFixture(options) {
	const enginePackageDir = options?.enginePackageDir;
	if (typeof enginePackageDir !== "string" || !isAbsolute(enginePackageDir)) {
		throw new Error(`createE2eFixture needs an absolute enginePackageDir`);
	}
	const engineEntry = join(enginePackageDir, "dist", "cli", "main.js");
	if (!existsSync(engineEntry)) {
		throw new Error(`engine not built at ${engineEntry}`);
	}
	const engineVersion = engineVersionOf(enginePackageDir);
	const launcherText = await launcherTextOf(enginePackageDir);
	const dir = mkdtempSync(join(tmpdir(), "codictator-e2e-"));
	mkdirSync(join(dir, ".codictator", "bin"), { recursive: true });
	mkdirSync(join(dir, "node_modules"), { recursive: true });
	writeFileSync(
		join(dir, ".codictator", "config.json"),
		fixtureConfig(engineVersion),
	);
	writeFileSync(join(dir, ".codictator", "bin", "run.mjs"), launcherText);
	symlinkSync(
		enginePackageDir,
		join(dir, "node_modules", "codictator"),
		"junction",
	);
	writeFileSync(join(dir, "notes.txt"), "e2e save probe\n");
	return {
		configPath: join(dir, ".codictator", "config.json"),
		dir,
		engineEntry,
		engineVersion,
		launcherPath: join(dir, ".codictator", "bin", "run.mjs"),
	};
}

export function removeE2eFixture(dir) {
	if (typeof dir !== "string" || dir === "") {
		return;
	}
	rmSync(resolve(dir), { force: true, recursive: true });
}
